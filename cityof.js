// Initialize tooltips and language
document.addEventListener('DOMContentLoaded', function() {
    // Initialize Bootstrap tooltips
    var tooltipTriggerList = [].slice.call(document.querySelectorAll('[data-bs-toggle="tooltip"]'));
    var tooltipList = tooltipTriggerList.map(function (tooltipTriggerEl) {
        return new bootstrap.Tooltip(tooltipTriggerEl);
    });
    
    // Initialize charts
    initCharts();
    
    // Set up language selection
    const languageOptions = document.querySelectorAll('.language-option');
    languageOptions.forEach(option => {
        option.addEventListener('click', function(e) {
            e.preventDefault();
            const lang = this.getAttribute('data-lang');
            changeLanguage(lang);
        });
    });
    
    // Check for saved language preference or default to English
    const savedLang = localStorage.getItem('preferredLanguage') || 'en';
    changeLanguage(savedLang);
});

// Change language function
function changeLanguage(lang) {
    // Update all elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
            
            // Update tooltip titles if they have data-translate attribute
            if (element.hasAttribute('data-bs-toggle') && element.getAttribute('data-bs-toggle') === 'tooltip') {
                element.setAttribute('title', translations[lang][key]);
                
                // If tooltip is already initialized, update its title
                const tooltipInstance = bootstrap.Tooltip.getInstance(element);
                if (tooltipInstance) {
                    tooltipInstance.setContent({'.tooltip-inner': translations[lang][key]});
                }
            }
        }
    });
    
    // Update the language dropdown text
    const languageDropdown = document.getElementById('languageDropdown');
    if (languageDropdown) {
        const globeIcon = languageDropdown.querySelector('i');
        const span = languageDropdown.querySelector('span');
        if (span) {
            span.textContent = translations[lang]['language'] || 'Language';
        }
    }
    
    // Update the html lang attribute
    document.documentElement.setAttribute('lang', lang);
    
    // Add language-specific class to body for font styling if needed
    document.body.classList.remove('hindi-lang', 'tamil-lang', 'telugu-lang', 'malayalam-lang');
    if (lang !== 'en') {
        document.body.classList.add(`${lang}-lang`);
    }
    
    // Save language preference
    localStorage.setItem('preferredLanguage', lang);
}


